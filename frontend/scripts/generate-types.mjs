import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const root = new URL('../../', import.meta.url);
// Git normalizes text to LF; keep the contract fingerprint identical across OSes.
const raw = (await readFile(new URL('backend/openapi.json', root), 'utf8')).replaceAll('\r\n', '\n');
const spec = JSON.parse(raw);

function type(schema) {
  if (schema.$ref) return schema.$ref.split('/').at(-1);
  if (schema.enum) return schema.enum.map(v => JSON.stringify(v)).join(' | ');
  if (schema.anyOf) return schema.anyOf.map(type).join(' | ');
  if (schema.type === 'array') return `Array<${type(schema.items)}>`;
  if (schema.type === 'object') {
    if (schema.properties) return `{ ${fields(schema).join(' ')} }`;
    return `Record<string, ${typeof schema.additionalProperties === 'object' ? type(schema.additionalProperties) : 'unknown'}>`;
  }
  return { integer: 'number', number: 'number', string: 'string', boolean: 'boolean', null: 'null' }[schema.type] ?? 'unknown';
}

function fields(schema) {
  return Object.entries(schema.properties).map(([key, value]) => `${JSON.stringify(key)}${schema.required?.includes(key) ? '' : '?'}: ${type(value)};`);
}

const lines = [
  '// Generated by npm run generate:types. Do not edit by hand.',
  `// Source: backend/openapi.json SHA256 ${createHash('sha256').update(raw).digest('hex')}`,
  '',
];
for (const [name, schema] of Object.entries(spec.components.schemas)) {
  lines.push(schema.type === 'object' && schema.properties
    ? `export interface ${name} {\n${fields(schema).map(line => `  ${line}`).join('\n')}\n}`
    : `export type ${name} = ${type(schema)};`, '');
}
const target = new URL('frontend/src/types/saga.ts', root);
await mkdir(new URL('frontend/src/types/', root), { recursive: true });
const text = lines.join('\n');
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== text) throw new Error('TypeScript contracts are stale; run npm run generate:types');
} else {
  await writeFile(target, text);
  await mkdir(new URL('frontend/src/data/', root), { recursive: true });
  for (const file of ['catalogue.json', 'rfq_scenarios.json']) {
    await writeFile(new URL(`frontend/src/data/${file}`, root), await readFile(new URL(`backend/app/db/seed/${file}`, root)));
  }
}
console.log(`${process.argv.includes('--check') ? 'Verified' : 'Generated'} ${Object.keys(spec.components.schemas).length} exact API types`);
